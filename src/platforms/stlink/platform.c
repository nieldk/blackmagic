static void flash_wait_done(void)
{
	while (FLASH_SR & FLASH_SR_BSY)
		continue;
}

static void flash_unlock(void)
{
	FLASH_KEYR = FLASH_KEY1;
	FLASH_KEYR = FLASH_KEY2;
}

static void flash_lock(void)
{
	FLASH_CR |= FLASH_CR_LOCK;
}

/*
 * On-demand recovery path: `monitor restore_bootloader`, invoked over BMP's
 * normal GDB connection (USB only - no SWD, no external probe, no opening
 * the case). Writes page 8 back to its exact pre-patch state, the same
 * read/check/erase/reprogram sequence as the automatic patch, just the
 * other direction and triggered by command instead of by boot.
 *
 * Safe to run on a fresh (unpatched) device too: it checks the live patch
 * site first and does nothing unless it reads exactly the known-patched
 * value, so it can't make an unpatched bootloader worse, and running it
 * twice is harmless.
 */
bool cmd_restore_bootloader(target_s *t, int argc, const char **argv)
{
	(void)t;
	(void)argc;
	(void)argv;

	const volatile uint16_t *patch_site = (const volatile uint16_t *)0x08002220U;

	if (*patch_site == 0xD1D8U) {
		gdb_out("Bootloader already original - nothing to restore.\n");
		return true;
	}

	if (*patch_site != 0xBF00U) {
		gdb_outf("Patch site reads 0x%04X - not the expected patched value, refusing to touch it.\n",
			*patch_site);
		return false;
	}

	if (!(FLASH_WRPR & WRPR_PAGE8_GROUP_BIT)) {
		gdb_out("Bootloader page group is write-protected - cannot restore.\n");
		return false;
	}

	gdb_out("Restoring original bootloader page 8...\n");

	__asm__ volatile ("cpsid i");

	flash_unlock();

	flash_wait_done();
	FLASH_CR |= FLASH_CR_PER;
	FLASH_AR = BOOTLOADER_PAGE8_ADDR;
	FLASH_CR |= FLASH_CR_STRT;
	flash_wait_done();
	FLASH_CR &= ~FLASH_CR_PER;

	FLASH_CR |= FLASH_CR_PG;
	for (uint32_t i = 0; i < BOOTLOADER_PAGE8_SIZE; i += 2) {
		volatile uint16_t *dst = (volatile uint16_t *)(BOOTLOADER_PAGE8_ADDR + i);
		uint16_t value;
		memcpy(&value, &bootloader_page8_original[i], 2);
		*dst = value;
		flash_wait_done();
	}
	FLASH_CR &= ~FLASH_CR_PG;

	flash_lock();

	__asm__ volatile ("cpsie i");

	const bool ok = (*patch_site == 0xD1D8U);
	gdb_outf("Restore %s. Bootloader will now wait for an explicit GO command again.\n", ok ? "succeeded" : "FAILED - verify did not match");
	return ok;
}

/*
 * Applies the bootloader auto-launch patch exactly once. Idempotent and safe
 * to call on every boot: it checks the live patch site first and does
 * nothing at all if it's already in the patched state.
 */
static void patch_bootloader_autoboot(void)
{
	const volatile uint16_t *patch_site = (const volatile uint16_t *)0x08002220U;

	/* Already patched (or this is some other image entirely) - do nothing. */
	if (*patch_site == 0xBF00U)
		return;

	/* Not the exact original byte we expect either - don't touch it. */
	if (*patch_site != 0xD1D8U)
		return;

	/* Refuse if this page group is hardware write-protected via option bytes. */
	if (!(FLASH_WRPR & WRPR_PAGE8_GROUP_BIT))
		return;

	__asm__ volatile ("cpsid i"); /* disable interrupts for the critical section */

	flash_unlock();

	/* Erase page 8 (the only page touched - page 9's shared utility is untouched). */
	flash_wait_done();
	FLASH_CR |= FLASH_CR_PER;
	FLASH_AR = BOOTLOADER_PAGE8_ADDR;
	FLASH_CR |= FLASH_CR_STRT;
	flash_wait_done();
	FLASH_CR &= ~FLASH_CR_PER;

	/* Reprogram the full page: original content, single instruction changed. */
	FLASH_CR |= FLASH_CR_PG;
	for (uint32_t i = 0; i < BOOTLOADER_PAGE8_SIZE; i += 2) {
		volatile uint16_t *dst = (volatile uint16_t *)(BOOTLOADER_PAGE8_ADDR + i);
		uint16_t value;
		memcpy(&value, &bootloader_page8_patched[i], 2);
		*dst = value;
		flash_wait_done();
	}
	FLASH_CR &= ~FLASH_CR_PG;

	flash_lock();

	__asm__ volatile ("cpsie i");
}

void platform_init(void)
{
	patch_bootloader_autoboot();

	rev = detect_rev();
	SCS_DEMCR |= SCS_DEMCR_VC_MON_EN;
	rcc_clock_setup_pll(&rcc_hse_configs[RCC_CLOCK_HSE8_72MHZ]);
#ifdef BLUEPILL
	led_idle_run = GPIO13;
	nrst_pin = NRST_PIN_V1;
#else
	switch (rev) {
	case 0:
		led_idle_run = GPIO8;
		nrst_pin = NRST_PIN_V1;
		break;
	case 0x101:
		led_idle_run = GPIO9;
		nrst_pin = NRST_PIN_CLONE;
		break;
	default:
		led_idle_run = GPIO9;
		nrst_pin = NRST_PIN_V2;
		break;
	}
#endif
	/* Setup GPIO ports */
	gpio_set_mode(TMS_PORT, GPIO_MODE_OUTPUT_2_MHZ, GPIO_CNF_INPUT_FLOAT, TMS_PIN);
	gpio_set_mode(TCK_PORT, GPIO_MODE_OUTPUT_2_MHZ, GPIO_CNF_OUTPUT_PUSHPULL, TCK_PIN);
	gpio_set_mode(TDI_PORT, GPIO_MODE_OUTPUT_2_MHZ, GPIO_CNF_OUTPUT_PUSHPULL, TDI_PIN);

	platform_nrst_set_val(false);

	gpio_set_mode(LED_PORT, GPIO_MODE_OUTPUT_2_MHZ, GPIO_CNF_OUTPUT_PUSHPULL, led_idle_run);

	/* Relocate interrupt vector table here */
	extern uint32_t vector_table;
	SCB_VTOR = (uintptr_t)&vector_table;

	platform_timing_init();
	/*
	 * The ST bootloader leaves the USB peripheral already initialised/enumerated
	 * (as itself, in DFU mode) when it jumps to the application. Without forcing
	 * a real electrical disconnect here, the host has no reason to notice the
	 * handoff and keeps treating us as the bootloader it already saw, so it
	 * never queries us for our actual (BMP) descriptors. This is lujji's fix
	 * from "Installing Black Magic via ST-Link bootloader": reset the USB
	 * peripheral, then directly force D+ (PA12) low as a plain GPIO long enough
	 * for the host to register a disconnect, before handing the pin back to the
	 * USB peripheral's own control. Done here, after the clock tree is fully
	 * configured, rather than before it.
	 */
	if ((rev & 0xff) > 1U) /* Reconnect USB (genuine-hardware path, board-specific) */
		gpio_set(GPIOA, GPIO15);
	rcc_periph_reset_pulse(RST_USB);
	rcc_periph_clock_enable(RCC_USB);
	rcc_periph_clock_enable(RCC_GPIOA);
	gpio_clear(GPIOA, GPIO12);
	gpio_set_mode(GPIOA, GPIO_MODE_OUTPUT_2_MHZ,
			GPIO_CNF_OUTPUT_OPENDRAIN, GPIO12);
	/* Hold D+ low long enough for the host to register a real disconnect.
	 * Generous on purpose: the bootloader's own enumeration with the host may
	 * still be settling when our patched bootloader jumps here almost
	 * immediately after boot (previously it would sit idle indefinitely
	 * waiting for a host command, giving the host unlimited settling time -
	 * now that wait is gone, so we give it back here instead). Boot time
	 * isn't performance-sensitive, so erring long costs nothing real.
	 * ~11ms before, now ~140ms at 72MHz. */
	for (volatile uint32_t i = 0; i < 2500000U; ++i)
		continue;
	/* Release D+ back to floating/input so the USB peripheral's own transceiver
	 * regains control of the line once blackmagic_usb_init() brings it up. */
	gpio_set_mode(GPIOA, GPIO_MODE_INPUT, GPIO_CNF_INPUT_FLOAT, GPIO12);
	blackmagic_usb_init();

#ifdef SWIM_AS_UART
	gpio_primary_remap(AFIO_MAPR_SWJ_CFG_FULL_SWJ, AFIO_MAPR_USART1_REMAP);
#endif

	/* Don't enable UART if we're being debugged. */
	if (!(SCS_DEMCR & SCS_DEMCR_TRCENA))
		aux_serial_init();
	adc_init();
}

void platform_nrst_set_val(bool assert)
{
	if (assert) {
		gpio_set_mode(NRST_PORT, GPIO_MODE_OUTPUT_2_MHZ, GPIO_CNF_OUTPUT_OPENDRAIN, nrst_pin);
		gpio_clear(NRST_PORT, nrst_pin);
	} else {
		gpio_set_mode(NRST_PORT, GPIO_MODE_INPUT, GPIO_CNF_INPUT_PULL_UPDOWN, nrst_pin);
		gpio_set(NRST_PORT, nrst_pin);
	}
}

bool platform_nrst_get_val()
{
	return gpio_get(NRST_PORT, nrst_pin) == 0;
}

static void adc_init(void)
{
	rcc_periph_clock_enable(RCC_ADC1);

	gpio_set_mode(GPIOA, GPIO_MODE_INPUT, GPIO_CNF_INPUT_ANALOG, GPIO0);

	adc_power_off(ADC1);
	adc_disable_scan_mode(ADC1);
	adc_set_single_conversion_mode(ADC1);
	adc_disable_external_trigger_regular(ADC1);
	adc_set_right_aligned(ADC1);
	adc_set_sample_time_on_all_channels(ADC1, ADC_SMPR_SMP_28DOT5CYC);
	adc_enable_temperature_sensor();
	adc_power_on(ADC1);

	/* Wait for the ADC to finish starting up */
	for (volatile size_t i = 0; i < 800000U; ++i)
		continue;

	adc_reset_calibration(ADC1);
	adc_calibrate(ADC1);
}

const char *platform_target_voltage(void)
{
	static char ret[6] = "0.00V";
	const uint8_t channel = 0;
	adc_set_regular_sequence(ADC1, 1, (uint8_t *)&channel);
	adc_start_conversion_direct(ADC1);
	/* Wait for end of conversion. */
	while (!adc_eoc(ADC1))
		continue;
	uint32_t platform_adc_value = adc_read_regular(ADC1);

	const uint8_t ref_channel = 17;
	adc_set_regular_sequence(ADC1, 1, (uint8_t *)&ref_channel);
	adc_start_conversion_direct(ADC1);
	/* Wait for end of conversion. */
	while (!adc_eoc(ADC1))
		continue;
	uint32_t vrefint_value = adc_read_regular(ADC1);

	/* Value in millivolts */
	uint32_t val = (platform_adc_value * 2400U) / vrefint_value;
	ret[0] = '0' + val / 1000U;
	ret[2] = '0' + (val / 100U) % 10U;
	ret[3] = '0' + (val / 10U) % 10U;

	return ret;
}

