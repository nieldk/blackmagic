/*
 * --- ST V2 bootloader cold-boot auto-launch patch ---
 *
 * The genuine V2 bootloader's launch decision (verified by disassembly of
 * Bootloader_2.0.bin) lives in a function at 0x08002210 that reads a DFU
 * state byte and only calls the app-launch routine (0x08000F2E) when that
 * byte equals 7 (dfuMANIFEST) - i.e. only after a host has driven it there
 * via an explicit DFU exit/manifestation sequence (what stlink-tool's
 * no-argument "GO" command does). On a true cold power-on with no host
 * present, that state is never reached, so the bootloader waits forever.
 *
 * This patches exactly one 2-byte instruction inside bootloader page 8
 * (0x08002000-0x080023FF): the `bne` at 0x08002220 (raw bytes D8 D1)
 * becomes a `nop` (00 BF), so the launch call is reached unconditionally
 * on every boot. Every other byte in the page - including the unrelated
 * shared utility function in the *next* page (page 9, 0x08002400+) which
 * is NOT touched by this patch - is written back identical to the
 * original. This array is the exact, verified original page-8 content
 * with only that one instruction changed; nothing here is guessed.
 */

